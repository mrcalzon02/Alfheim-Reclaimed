"""Run the pack's court refit through the installed Continuity Works capability.

The migration edits only blocks matching the archived original template and moves
existing NPCs in place. It never kills/re-summons an NPC or resets quest data.
"""
import gzip
import hashlib
import json
from pathlib import Path
import sys
import nbt
import gen_spawn_hub as hub
from hub_court_layout import STATIONS, ORIGINS, reservation

ROOT = Path(__file__).resolve().parents[1]
STAGE = ROOT/'build/spawn-court-refit'
DATA = ROOT/'kubejs/data/alfheim'
FUNCTIONS = DATA/'functions/hub/court_refit'
BASELINE = ROOT/'tools/spawn_court_refit_baseline'

def state_text(state):
    props = state.get('Properties',{})
    return state['Name'] + ('['+','.join(f'{k}={v}' for k,v in sorted(props.items()))+']' if props else '')

def index(root):
    return {tuple(map(int,b['pos'])):(root['palette'][int(b['state'])],b.get('nbt')) for b in root['blocks']}

class CourtProvider:
    provider_id='alfheim_spawn_court_refit_v2'
    aliases=('spawn_court_refit',)
    def describe(self): return {'provider_id':self.provider_id,'aliases':list(self.aliases)}
    def generate(self,request,registry_resolver):
        pieces=hub.make_pieces(); artifacts={}; rows=[]; edits=[]
        for key,p in pieces.items():
            if not key.startswith('court/'):continue
            part=key.split('/')[1]; path=DATA/'structures'/f'{key}.nbt'
            baseline=BASELINE/f'{part}.nbt'
            assert baseline.exists(), 'Preserve the pre-refit templates before generation'
            old=nbt.load(baseline)[1]; root=p.to_nbt()
            for state in root['palette']:
                probe=registry_resolver.probe(state['Name'],kind='block')
                assert probe['level'] in ('exact','vanilla'),probe
            nbt.save(path,'',root)
            path.write_bytes(gzip.compress(gzip.decompress(path.read_bytes()),mtime=0))
            artifacts[part+'.nbt']=path.read_bytes()
            ox,oy,oz=ORIGINS[part]; before=index(old); after=index(root)
            for pos,(state,be) in after.items():
                previous,previous_be=before.get(pos,({'Name':'minecraft:air'},None))
                if state==previous and be==previous_be:continue
                assert be is None and previous_be is None,'Do not replace inventories or block entities'
                x,y,z=pos
                edits.append({'pos':[x+ox,y+oy,z+oz],'before':state_text(previous),'after':state_text(state)})
            rows.append({'path':str(path.relative_to(ROOT)),'sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
                         'entities':len(root['entities'])})
        FUNCTIONS.mkdir(parents=True,exist_ok=True)
        lines=['# Generated by tools/refit_spawn_court.py. Origin: integer assembly datum.',
               'scoreboard players set #court_ready alfheim.hub 0']
        for e in edits:
            pos=' '.join('~'+str(v) for v in e['pos'])
            lines.append(f'execute if block {pos} {e["before"]} run setblock {pos} {e["after"]}')
        for i,s in enumerate(STATIONS):
            ox,oy,oz=ORIGINS[s['piece']];x,y,z=s['pos'];x+=ox;y+=oy;z+=oz
            sel=f'@e[type={hub.ELF_ENTITY},tag=alfheim_hub_court,name="{s["name"]}"]'
            lines += ['scoreboard players set #court_count alfheim.hub 0',
                      f'execute as {sel} run scoreboard players add #court_count alfheim.hub 1']
            # All 3x3 standing cells need headroom; a changed player block causes a safe skip.
            tests=' '.join(f'if block ~{xx+ox} ~{yy+oy} ~{zz+oz} minecraft:air'
                           for xx,yy,zz in sorted(reservation(s))
                           if abs(xx-s['pos'][0])<=1 and abs(zz-s['pos'][2])<=1)
            guard=f'execute if score #court_count alfheim.hub matches 1 if block ~{x} ~{y-1} ~{z} feywild:elven_quartz_block {tests}'
            lines += [f'{guard} run tp {sel} ~{x+.5} ~{y} ~{z+.5} {s["yaw"]} 0',
                      f'{guard} run scoreboard players add #court_ready alfheim.hub 1']
        lines += ['execute if score #court_ready alfheim.hub matches 8 run tag @s add alfheim_court_refit_v2',
                  'execute if score #court_ready alfheim.hub matches 8 run say [Alfheim] Court refit verified: 8 existing NPCs placed; quest progress preserved.',
                  'execute unless score #court_ready alfheim.hub matches 8 run say [Alfheim] Court refit incomplete: missing NPC or changed station; no NPC replaced.']
        (FUNCTIONS/'apply.mcfunction').write_text('\n'.join(lines)+'\n')
        # Bounded scheduling handles entities loading after the datapack load event.
        anchor='@e[type=minecraft:marker,tag=alfheim_hub_baked,tag=!alfheim_hub_buried,tag=!alfheim_court_refit_v2,limit=1]'
        poll=['scoreboard players add #court_attempts alfheim.hub 1',
              f'execute in mythicbotany:alfheim as {anchor} at @s positioned ~-.5 ~-1 ~5.5 run function alfheim:hub/court_refit/apply',
              f'execute if score #court_attempts alfheim.hub matches ..12 in mythicbotany:alfheim unless entity @e[type=minecraft:marker,tag=alfheim_court_refit_v2] run schedule function alfheim:hub/court_refit/poll 5s replace']
        (FUNCTIONS/'poll.mcfunction').write_text('\n'.join(poll)+'\n')
        (FUNCTIONS/'load.mcfunction').write_text('scoreboard objectives add alfheim.hub dummy\nscoreboard players set #court_attempts alfheim.hub 0\nschedule function alfheim:hub/court_refit/poll 5s replace\n')
        tag=ROOT/'kubejs/data/minecraft/tags/functions/load.json';doc=json.loads(tag.read_text())
        if 'alfheim:hub/court_refit/load' not in doc['values']:doc['values'].append('alfheim:hub/court_refit/load')
        tag.write_text(json.dumps(doc,indent=2)+'\n')
        for p in FUNCTIONS.glob('*.mcfunction'):artifacts[p.name]=p.read_bytes()
        (STAGE/'migration.json').write_text(json.dumps(edits,indent=2)+'\n')
        return {'provider_id':self.provider_id,'status':'LOCALLY_VALIDATED',
                'generated_layout':{'pieces':rows,'stations':STATIONS,'guarded_block_edits':len(edits)},
                'structure_artifact':{'format':'minecraft_structure_nbt','piece_count':4},'artifact_bytes':artifacts}

def main():
    cw=Path('C:/GITS/Structuresmith/StructureSmith');sys.path.insert(0,str(cw/'src'))
    from structure_capability import StructureCapability
    assert all((BASELINE/f'{part}.nbt').exists() for part in ORIGINS), 'Original migration baseline missing'
    cap=StructureCapability(project_root=ROOT,state_root=STAGE/'snapshots')
    assert cap.capabilities()['service']=='Continuity Works'
    cap.inventory.add_registry_ids(json.loads((ROOT/'server/local/kubejs/export/registries/block.json').read_text()),kind='block')
    cap.register_generator(CourtProvider())
    request={'structure_id':'alfheim:spawn_court_refit','target_version':'1.20.1','operation':'generate','grade':2,
             'purpose':{'kind':'protected_elven_court','required_zones':['guard reception','magister audience','archive','kitchen','stores','steward','watch','survey records'],
                        'required_routes':['three-wide NPC approaches','existing four processional aisles']},
             'context':{'dimension':'mythicbotany:alfheim','terrain':'existing authored Greatbole family footprint'},
             'preserve':['NPC names and UUIDs','quest IDs and player progression','Greatbole','foundation and independent structure reservations'],
             'integration_contracts':{'independent_structure_gap':500,'same_family':'existing Greatbole and Hollow Court; no independent structure placement'},
             'generation':{'kind':'spawn_court_refit','seed':hub.SEED,'materialize_nbt':True}}
    plan=cap.plan(request);assert plan['audit']['status']!='FAIL',plan
    result=cap.generate(request);assert result['generation']['status']=='LOCALLY_VALIDATED'
    report={'execution':'Continuity Works StructureCapability.plan / generate','seed':hub.SEED,'minecraft':'1.20.1',
            'cw_source_sha256':hashlib.sha256((cw/'src/structure_capability/api.py').read_bytes()).hexdigest(),
            'snapshot':result['snapshot'],**result['generated_layout'],
            'existing_world_application':'guarded automatic migration on next load; no save edited offline'}
    (ROOT/'tools/spawn_court_refit_report.json').write_text(json.dumps(report,indent=2)+'\n')
    (ROOT/'kubejs/server_scripts/04_spawn_hub.js').write_text(hub.protection_script(),encoding='utf-8')
    manifest=json.loads((ROOT/'tools/hollow_court_manifest.json').read_text())
    links=[{'quest_line_id':n['line'],'entity_id':hub.ELF_ENTITY,'name':n['name'],'scale':1.0} for n in manifest['named']]
    (ROOT/'kubejs/data/quest_giver/quest_line_links.json').write_text(json.dumps(links,indent=2)+'\n')
    print(f'Continuity Works: four court templates, eight stations, {len(report["pieces"])} verified artifacts, {report["guarded_block_edits"]} guarded migration edits.')

if __name__=='__main__':main()
