def ellipsoid(p,c,r,block,shell=0,angular=False):
    cx,cy,cz=c;rx,ry,rz=r
    for x in range(max(0,cx-rx),min(p.size[0],cx+rx+1)):
        for y in range(max(5,cy-ry),min(p.size[1],cy+ry+1)):
            for z in range(max(0,cz-rz),min(p.size[2],cz+rz+1)):
                d=abs((x-cx)/rx)+abs((y-cy)/ry)+abs((z-cz)/rz) if angular else ((x-cx)/rx)**2+((y-cy)/ry)**2+((z-cz)/rz)**2
                if d<=1 and (not shell or d>=shell):p.set(x,y,z,block(x,y,z) if callable(block) else block)

