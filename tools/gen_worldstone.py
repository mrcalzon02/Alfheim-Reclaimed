class Provider:
    provider_id='alfheim_mountain_worldstone_v1';aliases=('alfheim_mountain_worldstone',)
    def __init__(self,stage):self.stage=stage
    def describe(self):return dict(provider_id=self.provider_id,aliases=list(self.aliases))
    def generate(self,request,resolver):
        material_ids=['alfheim:obsidian_livingrock','alfheim:cracked_livingrock','alfheim:starfleck_livingrock']
        probes={rid:resolver.probe(rid,kind='block') for rid in material_ids+['alfheim_companion:'+b for b in BLOCKS]}
        probes.update({'item:'+rid:resolver.probe(rid,kind='item') for rid in ['alfheim_companion:'+b for b in ITEM_IDS]})
        probes.update({rid:resolver.probe(rid,kind='item') for rid in EXTERNAL})
        assert all(p['level'] in ('exact','vanilla') for p in probes.values()),probes
        files={};defs={JAVA+'WorldstoneLayout.java':GEOMETRY.encode()}
        for name in BLOCKS:
            defs[ASSET+f'blockstates/{name}.json']={'variants':{'':{'model':f'alfheim_companion:block/{name}'}}}
            defs[ASSET+f'models/block/{name}.json']={'parent':'minecraft:block/cube_all','textures':{'all':'alfheim_companion:block/worldstone_crimson'}}
            defs[ASSET+f'models/item/{name}.json']={'parent':f'alfheim_companion:block/{name}'}
            defs[f'kubejs/data/alfheim_companion/loot_tables/blocks/{name}.json']={'type':'minecraft:block','pools':[{'rolls':1,'conditions':[{'condition':'minecraft:survives_explosion'}],'entries':[{'type':'minecraft:item','name':'alfheim_companion:'+name}]}]}
        defs.update(resources(ROOT,ASSET))
        # Additive namespace tag, included from the vanilla tool tags by main().
        defs[DATA+'tags/blocks/worldstone.json']={'replace':False,'values':['alfheim_companion:'+b for b in BLOCKS]}
        defs[DATA+'worldgen/structure/mountain_worldstone.json']={'type':'alfheim_companion:mountain_worldstone','biomes':'#alfheim:has_mountain_worldstone','step':'underground_structures','terrain_adaptation':'none','spawn_overrides':{}}
        defs[DATA+'worldgen/structure_set/mountain_worldstone.json']={'structures':[{'structure':'alfheim:mountain_worldstone','weight':1}],'placement':{'type':'minecraft:random_spread','spacing':64,'separation':48,'salt':202610181,'spread_type':'linear'}}
        from gen_ancient_districts import HOME_BIOMES
        defs[DATA+'tags/worldgen/biome/has_mountain_worldstone.json']={'replace':False,'values':[b for b in HOME_BIOMES if b not in ('alfheim:alfheim_ocean','alfheim:tidewood_shore','alfheim:mistbark_shore','alfheim:sporebank_shore') and 'void' not in b]}
        defs[DATA+'tags/worldgen/structure/worldstones.json']={'replace':False,'values':['alfheim:mountain_worldstone']}
        image=Image.open(ROOT/'tools/worldstone_art/crimson_master.png').convert('RGB').resize((32,32),Image.Resampling.NEAREST)
        out=io.BytesIO();image.save(out,format='PNG');defs[ASSET+'textures/block/worldstone_crimson.png']=out.getvalue()
        records=[]
        for rel,body in defs.items():
            if body is None:continue
            data=body if isinstance(body,bytes) else (json.dumps(body,indent=2)+'\n').encode()
            p=self.stage/rel;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
            files[rel.replace('/','_')]=data;records.append(dict(file=rel,sha256=hashlib.sha256(data).hexdigest()))
        return dict(provider_id=self.provider_id,status='GENERATED_NOT_VALIDATED',
                    generated_layout=dict(files=records,registry_probes=probes,local_envelope=[-119,-48,-119,119,168,119],
                    cavern_nominal_axes=[228,200,220],crystal_height=136,minimum_summit=260,minimum_roof=32,
                    zones=['irregular sealed cavern','floating faceted crimson crystal','four suspended splinters','connected perimeter shelf','viewing spur','central chasm'],
                    minimum_independent_gap=500,clearance=1024,global_density_unchanged=True),
                    structure_artifact=dict(format='native_chunk_clipped_procedural',piece_count=1),artifact_bytes=files)


def main():
    sys.path.insert(0,'C:/GITS/Structuresmith/StructureSmith/src')
    from structure_capability import StructureCapability
    stage=ROOT/'build/worldstone/generated';cap=StructureCapability(project_root=ROOT,state_root=stage/'snapshots')
    cap.inventory.add_registry_ids(json.loads((ROOT/'server/local/kubejs/export/registries/block.json').read_text()),kind='block')
    cap.inventory.add_registry_ids(json.loads((ROOT/'server/local/kubejs/export/registries/item.json').read_text()),kind='item')
    source=(ROOT/JAVA.replace('worldgen/','worldstone/')/'ModWorldstoneBlocks.java').read_text()
    for b in BLOCKS+ITEM_IDS:assert '"'+b+'"' in source
    cap.inventory.add_registry_ids(['alfheim_companion:'+b for b in BLOCKS],kind='block');cap.register_generator(Provider(stage))
    cap.inventory.add_registry_ids(['alfheim_companion:'+b for b in ITEM_IDS],kind='item')
    result=cap.generate(dict(structure_id='alfheim:mountain_worldstone',target_version='1.20.1',grade=3,
        purpose=dict(kind='mountain_worldstone',required_zones=['gargantuan suspended crimson crystal','epic underground cavern','safe mountain roof']),
        context=dict(dimension='mythicbotany:alfheim',terrain='only actual noise-terrain summits at Y260 or higher'),
        integration_contracts=dict(minimum_independent_gap=500),generation=dict(kind='alfheim_mountain_worldstone',materialize_nbt=False)))
    for r in result['generated_layout']['files']:
        p=ROOT/r['file'];p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes((stage/r['file']).read_bytes())
    for tag in ('mineable/pickaxe','needs_diamond_tool'):
        p=ROOT/f'kubejs/data/minecraft/tags/blocks/{tag}.json';p.parent.mkdir(parents=True,exist_ok=True)
        body=json.loads(p.read_text()) if p.exists() else dict(replace=False,values=[])
        assert not body.get('replace',False)
        if '#alfheim:worldstone' not in body['values']:body['values'].append('#alfheim:worldstone')
        p.write_text(json.dumps(body,indent=2)+'\n')
    lang=ROOT/(ASSET+'lang/en_us.json');body=json.loads(lang.read_text())
    body.update({'block.alfheim_companion.'+name:NAMES[name] for name in BLOCKS})
    body.update({'item.alfheim_companion.'+name:NAMES[name] for name in ITEM_IDS if name not in BLOCKS})
    lang.write_text(json.dumps(body,indent=2)+'\n')
    report=dict(capability='Continuity Works',snapshot_id=result['snapshot']['snapshot_id'],generation=result['generation'],layout=result['generated_layout'],texture=dict(tool='built-in image_gen',master='tools/worldstone_art/crimson_master.png',runtime_size=[32,32],prompt='Seamless opaque pixel-art deep blood-red crystal facets, dark garnet planes and luminous scarlet fracture veins; no background, text or border. Nearest-neighbor runtime downsample.'),runtime='not yet validated')
    (ROOT/'tools/worldstone_generation.json').write_text(json.dumps(report,indent=2)+'\n')
    print('CW generated native Worldstone geometry/data/assets:',len(result['generated_layout']['files']),'artifacts;',result['snapshot']['snapshot_id'])


if __name__=='__main__':main()
