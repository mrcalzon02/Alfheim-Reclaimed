"""Regenerate small, hosted Void Margin botanical and mineral remnants.
Never edits biome masks, density, aquifers, structure templates or natural ore output.
"""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'kubejs/data/alfheim'
ASSETS=ROOT/'kubejs/assets/alfheim/models/block'
SPECS=json.loads('''[{"name":"shatter_bramble","block":"alfheim:bramble","biome":"alfheim:shatterfields","support":["alfheim:shardbreccia_livingrock","alfheim:anchorstone_livingrock","alfheim:seamstone_livingrock"],"tries":10,"xz":4,"y":1,"chance":11},{"name":"rootfall_rootlet","block":"alfheim:rootfall_rootlet","biome":"alfheim:rootfall","support":["alfheim:rootfossil_livingrock","alfheim:resinshale_livingrock","alfheim:hollowheart_livingrock"],"tries":14,"xz":4,"y":1,"chance":3},{"name":"prism_lichen","block":"alfheim:prism_lichen","biome":"alfheim:prism_drift","support":["alfheim:prismstone_livingrock","alfheim:aetherquartzite_livingrock","alfheim:glintschist_livingrock"],"tries":7,"xz":3,"y":1,"chance":7},{"name":"mourning_reed","block":"alfheim:mourning_reed","biome":"alfheim:sepulchral_reach","support":["alfheim:epitaph_livingrock","alfheim:mourning_livingrock","alfheim:oathstone_livingrock"],"tries":9,"xz":4,"y":1,"chance":5}]''')
SHAPES=json.loads('''{"rootfall_rootlet":{"name":"Petrified Rootlet","stem":"alfheim:block/rootfossil_livingrock","accent":"alfheim:block/resinshale_livingrock","parts":[[[6,0,6],[10,3,10],"stem"],[[7,3,7],[9,9,9],"stem"],[[4,3,7],[7,5,9],"accent"],[[3,5,7],[5,8,9],"stem"],[[9,4,7],[12,6,9],"accent"],[[11,6,7],[13,9,9],"stem"]]},"prism_lichen":{"name":"Prism Lichen","stem":"alfheim:block/prismstone_livingrock","accent":"alfheim:block/aetherquartzite_livingrock","parts":[[[3,0,4],[13,1,12],"stem"],[[5,1,5],[8,2,8],"accent"],[[6,2,6],[8,6,8],"accent"],[[10,1,8],[12,5,10],"accent"],[[3,1,9],[5,3,11],"accent"],[[8,1,3],[10,2,6],"stem"]]},"mourning_reed":{"name":"Mourning Stone-Reed","stem":"alfheim:block/epitaph_livingrock","accent":"alfheim:block/mourning_livingrock","parts":[[[3,0,5],[6,1,8],"accent"],[[4,1,6],[5,11,7],"stem"],[[3,10,5],[6,13,8],"accent"],[[8,0,9],[11,1,12],"accent"],[[9,1,10],[10,7,11],"stem"],[[8,7,9],[11,9,12],"accent"],[[12,0,3],[14,1,6],"accent"],[[12,1,4],[13,8,5],"stem"],[[11,8,3],[14,10,6],"accent"]]}}''')

def write(path,obj):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(obj,indent=2)+'\n',encoding='utf-8')

def patch(s):
    return {'type':'minecraft:random_patch','config':{
        'tries':s['tries'],'xz_spread':s['xz'],'y_spread':s['y'],
        'feature':{'feature':{'type':'minecraft:simple_block','config':{'to_place':{
            'type':'minecraft:simple_state_provider','state':{'Name':s['block']}}}},
        'placement':[{'type':'minecraft:block_predicate_filter','predicate':{
            'type':'minecraft:all_of','predicates':[
                {'type':'minecraft:matching_blocks','blocks':['minecraft:air']},
                {'type':'minecraft:matching_blocks','blocks':s['support'],'offset':[0,-1,0]}
            ]}}]}}}

def placed(s):
    return {'feature':'alfheim:'+s['name'],'placement':[
        {'type':'minecraft:rarity_filter','chance':s['chance']},
        {'type':'minecraft:in_square'},
        {'type':'minecraft:heightmap','heightmap':'MOTION_BLOCKING_NO_LEAVES'},
        {'type':'minecraft:biome'}]}

def modifier(s):
    return {'type':'forge:add_features','biomes':[s['biome']],
            'features':'alfheim:'+s['name'],'step':'vegetal_decoration'}

def model(s):
    faces=('north','south','east','west','up','down')
    return {'parent':'minecraft:block/block','ambientocclusion':False,
        'textures':{'particle':s['stem'],'stem':s['stem'],'accent':s['accent']},
        'elements':[{'from':lo,'to':hi,'faces':{d:{'texture':'#'+tex} for d in faces}}
                    for lo,hi,tex in s['parts']]}

def main():
    for s in SPECS:
        n=s['name']
        write(DATA/'worldgen/configured_feature'/(n+'.json'),patch(s))
        write(DATA/'worldgen/placed_feature'/(n+'.json'),placed(s))
        write(DATA/'forge/biome_modifier'/('zz_void_'+n+'.json'),modifier(s))
    lines=['// GENERATED by tools/gen_void_vegetation.py — authored Void Margin remnants',
           "StartupEvents.registry('block', event => {"]
    for n,s in SHAPES.items():
        write(ASSETS/(n+'.json'),model(s))
        lines.extend([
            "  event.create('alfheim:"+n+"').displayName('"+s['name']+"')",
            "    .model('alfheim:block/"+n+"').renderType('solid').soundType('stone')",
            "    .fullBlock(false).notSolid().hardness(0.5).box(3, 0, 3, 13, 13, 13)",
            "    .tagBlock('minecraft:mineable/pickaxe')"])
    lines.append('})')
    (ROOT/'kubejs/startup_scripts/29_void_vegetation.js').write_text(
        '\n'.join(lines)+'\n',encoding='utf-8')
    print('Regenerated four Void remnant features, three models and startup blocks')

if __name__=='__main__':
    main()
