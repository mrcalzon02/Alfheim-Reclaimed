def png(im):
    out=io.BytesIO();im.save(out,format='PNG');return out.getvalue()

def texture(name,family,base,variant):
    rng=random.Random(int.from_bytes(hashlib.sha256(f'{name}/{variant}'.encode()).digest()[:8],'big'))
    im=Image.new('RGB',(32,32));pixels=im.load()
    for y in range(32):
        for x in range(32):
            n=rng.randrange(-10,11)
            if family=='flesh':n+=int(10*math.sin(x*.8+y*.23)+5*math.cos(x*.4-y*.5))
            elif family=='sludge':n+=int(8*math.sin(x*.27+y*.3)*math.cos(y*.23-x*.2))
            elif family=='bone':n+=int(6*math.sin(x*.65+y*.1))
            pixels[x,y]=tuple(max(0,min(255,c+n)) for c in base)
    d=ImageDraw.Draw(im)
    dark=tuple(max(0,c-32) for c in base);light=tuple(min(255,c+25) for c in base)
    if family in ('hide','organ','sludge'):
        for _ in range(14):
            x,y=rng.randrange(-4,32),rng.randrange(-4,32);r=rng.randrange(2,7)
            d.arc((x,y,x+r*2,y+r),0,300,fill=dark,width=1)
            if family=='sludge':d.line((x+1,y+1,x+r,y+1),fill=light)
        if family=='hide':
            for x in (7,21):d.line([(x,0),(x-2,7),(x+1,13),(x-1,22),(x+2,31)],fill=dark,width=1)
        if family=='organ':
            d.line([(0,7),(8,12),(17,10),(23,19),(31,21)],fill=dark,width=2)
            d.line([(16,10),(13,20),(18,31)],fill=light,width=1)
    elif family=='bone':
        for _ in range(24):
            x,y=rng.randrange(32),rng.randrange(32);d.point((x,y),fill=dark)
        if 'fractured' in name:d.line([(2,0),(7,9),(4,17),(13,24),(12,31)],fill=dark,width=2)
        if 'marrow' in name:d.ellipse((9,5,23,26),fill=dark);d.ellipse((13,9,20,23),fill=(106,66,74))
    elif family in ('crystal','socket'):
        for x,y in ((0,0),(16,0),(8,16),(24,16)):
            tone=tuple(max(0,min(255,c+rng.randrange(-20,21))) for c in base)
            d.polygon([(x,y),(x+13,y+3),(x+16,y+13),(x+4,y+17)],fill=tone,outline=dark)
            d.line([(x+1,y+1),(x+12,y+4),(x+14,y+11)],fill=light)
        d.line([(3,0),(12,10),(9,16),(23,25),(21,31)],fill=dark,width=2)
        if family=='socket':
            d.rectangle((7,7,24,24),outline=light,width=2);d.rectangle((11,11,20,20),fill=dark)
            d.line((15,0,15,6),fill=dark,width=3);d.line((25,16,31,16),fill=dark,width=3)
    elif family=='brick':
        for y in (0,8,16,24):
            d.line((0,y,31,y),fill=dark,width=1)
            for x in range(-8 if y%16 else 0,32,16):d.line((x,y,x,y+8),fill=dark)
        d.line([(3,0),(7,8),(5,11),(14,18),(12,24)],fill=dark)
    return im

def build():
    out={};catalog=[]
    def emit(path,value):out[path]=value if isinstance(value,bytes) else (json.dumps(value,indent=2)+'\n').encode()
    script=["// Generated by tools/gen_war_remains_materials.py; full restart required.","StartupEvents.registry('block', event => {"]
    sheet=Image.new('RGB',(1024,5*156+44),(20,24,31));draw=ImageDraw.Draw(sheet)
    font=ImageFont.truetype('C:/Windows/Fonts/segoeui.ttf',12)
    draw.text((12,10),'VOID FRONTIER / TITAN BIOMASS, DEAD CRYSTAL AND WAR MASONRY',fill='white',font=font)
    for i,(name,family,base) in enumerate(SPECS):
        rid='alfheim:'+name;soft=family in ('sludge','flesh','organ','hide')
        tag='war_biomass' if soft or family=='bone' else 'war_crystal_remains' if family in ('crystal','socket') and name.startswith('golem') else 'war_masonry'
        title=name.replace('_',' ').title()
        script.append(f"  event.create('{rid}').displayName('{title}').soundType('{'gravel' if soft else 'stone'}').hardness({0.8 if soft else 2.5}).resistance({2.0 if soft else 8.0}).tagBlock('minecraft:mineable/{'shovel' if soft else 'pickaxe'}').tagBoth('alfheim:{tag}').textureAll('alfheim:block/{name}')")
        variants=[]
        for v in range(3):
            suffix='' if v==0 else f'_v{v}';key=name+suffix
            im=texture(name,family,base,v)
            emit(f'kubejs/assets/alfheim/textures/block/{key}.png',png(im))
            emit(f'kubejs/assets/alfheim/models/block/{key}.json',{'parent':'minecraft:block/cube_all','textures':{'all':'alfheim:block/'+key}})
            variants.append({'model':'alfheim:block/'+key})
            if v==0:sheet.paste(im.resize((96,96),Image.Resampling.NEAREST),((i%8)*128+16,(i//8)*156+48))
        emit(f'kubejs/assets/alfheim/blockstates/{name}.json',{'variants':{'':variants}})
        emit(f'kubejs/assets/alfheim/models/item/{name}.json',{'parent':'alfheim:block/'+name})
        emit(f'kubejs/data/alfheim/loot_tables/blocks/{name}.json',{'type':'minecraft:block','pools':[{'rolls':1,'conditions':[{'condition':'minecraft:survives_explosion'}],'entries':[{'type':'minecraft:item','name':rid}]}]})
        catalog.append({'id':rid,'family':family,'name':title,'variants':3,'decay_state':name.split('_')[-1]})
        label=title.replace('Titan ','').replace('Golem ','').replace('Bio Sludge ','Sludge ')
        words=label.split();draw.text(((i%8)*128+8,(i//8)*156+146),' '.join(words[:2]),fill='#d9dfe6',font=font)
        draw.text(((i%8)*128+8,(i//8)*156+162),' '.join(words[2:]),fill='#a4b0bd',font=font)
    script.append('})\n')
    emit('kubejs/startup_scripts/26_war_remains.js','\n'.join(script).encode())
    emit('kubejs/war_remains_catalog.json',{'blocks':catalog,'mechanics':'stable decorative decay states; no fluid ticks or spreading'})
    emit('tools/war_remains_materials_review.png',png(sheet.crop((0,0,1024,4*156+44))))
    return out

if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    output=build()
    for rel,data in output.items():
        path=ROOT/rel
        if args.check:assert path.exists() and path.read_bytes()==data,rel
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
    print(f"WAR MATERIALS {'PASS' if args.check else 'GENERATED'}: {len(SPECS)} blocks, 96 textures, {len(output)} files")
