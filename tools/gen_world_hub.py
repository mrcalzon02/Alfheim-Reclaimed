    f'tag @a[tag={AWAIT}] remove {AWAIT}',
    '',
    f'scoreboard players set #created {OBJ} 1',
    '# #final is what stops hub/resolve. Only a real, structure-carried anchor sets it, so a',
    '# provisional fallback never ends the search for the tree.',
    f'scoreboard players set #final {OBJ} 1',
    'tellraw @a[tag=!alfheim_quiet] {"text":"[Alfheim] World hub anchored to the Greatbole.",'
