    f'execute in {HOME} as @a[tag={AWAIT}] at {SELECT_BAKED} run spawnpoint @s ~ ~1 ~',
    f'execute as @a[tag={AWAIT}] run tellraw @s {{"text":"[Alfheim] The Greatbole has finished '
